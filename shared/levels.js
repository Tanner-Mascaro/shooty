// Level layouts. Maps are point-symmetric: only the top half is written out and the
// bottom half is the top rotated 180°, so both spawns are fair.
//
//   #  obstacle: on the edge, the boundary wall; inside, a volcano (hell; touching # merge
//      into one), an iceberg (ice), a server rack (robot; touching # join into one row), a tree
//      (swamp) or a full-height wall (haunt / castle; touching # join up into rooms and hallways)
//   B  building / hut (witch cottages, hell ruins, ice lodges, nuketown houses) — outdoor maps
//   +  low cover you can shoot over: boulder / ice chunk / crate / bush / furniture / rubble
//   .  ground      L  pit (lava / acid / bog / black ice / a hole into the void depending on the level)
//   S / G / M  gun pad sites (weapon re-rolls each spawn)  H  health  N  grenade
//
// shared/terrain.js turns these into smooth shapes. Keep paths 2+ squares wide around
// volcanoes: a cone spreads about a square past its # cells.
//
// To add a level: add a map here, a name in LEVEL_NAMES, a theme in public/js/themes.js
// (its id picks the obstacle style in terrain.js), a floor in FLOORS (public/js/level.js),
// a sprite in render/sprites.js and a button in public/index.html.

function mirror(half) {
  return half.concat(half.slice().reverse().map(r => r.split('').reverse().join('')));
}

