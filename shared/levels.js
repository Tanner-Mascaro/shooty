  deckhouse(35, 29, 44, 29); deckhouse(35, 37, 44, 37); deckhouse(35, 30, 35, 32); deckhouse(35, 34, 35, 36); deckhouse(44, 30, 44, 32); deckhouse(44, 34, 44, 36);
